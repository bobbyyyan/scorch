#!/usr/bin/env python3
"""Concern #2: isolate the pool ceiling, and check production against the closed form.

This file exists because the numbers it produces were first generated by scripts that
lived only in a scratchpad. They were reported in a commit that touched no code, so the
grid was not the committed probe's grid and no figure could be regenerated. A number in a
document has to be reproducible from the repository.

WHAT THE GATE IS. scorch_policy.h:2611-2619:

    if (gate_maxthreads > 0) { if (pool > gate_maxthreads) mingrains = 0; }
    if (mingrains > 0) {
      const long work_proxy = nnz * (long)(k > 16 ? k : 16);
      if (work_proxy < mingrains * SCORCH_GRAIN_SPMM) partition_mode = 0;
    }

THREE INDEPENDENT LEGS, because the first two share a weakness.

  1. ISOLATION. The earlier sweep varied the caller's pool and recomputed the resolved
     thread count from it. That one variable reaches BOTH arguments of
     scorch_spmm_partition_mode -- the pool ceiling reads the pool, a separate
     single-worker gate reads the resolved count -- so nothing it reported was
     attributable. Here the resolved count is held fixed and only the pool varies.

  2. TWO ENV ROUTES to "gate off" that must agree: a ceiling below the pool, and the
     work gate's own documented zero. They test that two readings of the source agree
     with each other -- but both go through the same exported function, so neither can
     tell whether that function reads the constants the header declares.

  3. THE COMPOSED CLOSED FORM, which is what leg 2 cannot do. Production must return
     exactly the predicted set. If the linked object's MINGRAINS or GRAIN_SPMM differs
     from the header -- which is what a defines-only rebuild relinking stale objects
     produces -- the two env routes still agree with each other and both disagree.

     COMPOSED is the operative word. A closed form for ONE predicate in a chain is an
     upper bound, not a prediction, and an uncomposed one turns a disagreement into a
     narrative instead of a defect. The function holds four predicates:

       solo       partition_solo_off && nthreads <= 1    DISABLED by default (:531 is 0)
       ceiling    pool > gate_maxthreads                 reads pool
       work gate  work_proxy < mingrains * GRAIN_SPMM     reads nnz, k
       maxout     rows * out_cols * elem_size >= maxout   reads rows, out_cols, elem_size

     Composing the work gate with maxout predicts 65 of the 66 the work gate alone
     predicts, and 65 is what production returns. The single excluded cell is predicted
     rather than accounted for afterwards.

  Plus the invariances the predicate's form demands, each with the control that shows the
  check is not vacuous.

Usage: gate_isolate.py [small-pool] [big-pool]
"""
import json
import os
import subprocess
import sys

ROWS = (64, 256, 512, 4096, 65536, 1000000)
# 18749 and 18750 are BRACKET POINTS, not samples. At k=16 they give work proxies of
# 299984 and 300000, so exactly one fires under a strict `<` against the declared
# threshold of 300000 and neither distinguishes any other candidate. Without them the
# grid's largest firing proxy is 96000 and its smallest non-firing one is 320000, so ANY
# threshold in (96000, 320000] -- a factor of 3.33, covering MINGRAINS of 1 or 2 and
# GRAIN_SPMM of 50000 or 150000 -- predicts the identical fired set. A geometric grid
# cannot resolve candidates 2x apart, so the closed form BOUNDED the product rather than
# confirming it. The pair also supplies the only cell where work == threshold exactly,
# which is what separates `<` from `<=`; nothing else in the grid tests the strictness.
NNZ = (3000, 18749, 18750, 20000, 50000, 200000, 1000000, 20000000)
KS = (1, 2, 4, 8, 16, 32)
CELLS = [(r, n, k) for r in ROWS for n in NNZ for k in KS]

# Both read from scorch_policy.h -- :1581 and :82. Stated here so a divergence between
# the header and the linked object shows up as a disagreement rather than being absorbed.
MINGRAINS, GRAIN = 2, 150000
THRESHOLD = MINGRAINS * GRAIN


def predicted(maxout, elem=4):
    """The cells the gate must force, COMPOSED with the predicates downstream of it.

    The work gate alone is an upper bound: a cell it forces may already be mode 0 from
    maxout, in which case it is not live at either pool and cannot be attributed to the
    ceiling. Returns (composed, work_gate_only) so the difference is visible.
    """
    work_only = {c for c in CELLS if c[1] * max(c[2], 16) < THRESHOLD}
    composed = {c for c in work_only if c[0] * c[2] * elem < maxout}
    return composed, work_only


def run(code, env=None):
    e = dict(os.environ)
    if env:
        e.update(env)
    o = subprocess.run([sys.executable, "-c", code], capture_output=True, text=True, env=e)
    if o.returncode:
        print("   FAILED: %s" % o.stderr.strip().split("\n")[-1])
        return None
    return json.loads(o.stdout)


def modes(nt, pool, cells, env=None):
    return run("import json,scorch_ops as S;print(json.dumps("
               "[S.scorch_spmm_partition_mode(r,n,k,k,4,%d,%d) for (r,n,k) in %r]))"
               % (nt, pool, cells), env)


def main(argv):
    small = int(argv[1]) if len(argv) > 1 else 8
    big = int(argv[2]) if len(argv) > 2 else 64
    print("grid %d rows x %d nnz x %d k = %d cells   pools small=%d big=%d"
          % (len(ROWS), len(NNZ), len(KS), len(CELLS), small, big))
    print("closed form: nnz*max(k,16) < %d*%d = %d  (no thread term, no row term)\n"
          % (MINGRAINS, GRAIN, THRESHOLD))

    # the discrimination window: what range of thresholds this grid cannot tell apart
    procs = sorted({c[1] * max(c[2], 16) for c in CELLS})
    fires = [w for w in procs if w < THRESHOLD]
    nofire = [w for w in procs if w >= THRESHOLD]
    print("DISCRIMINATION: largest firing proxy %d, smallest non-firing %d, so this grid"
          % (max(fires), min(nofire)))
    print("   cannot distinguish any threshold in (%d, %d] -- a factor of %.2f."
          % (max(fires), min(nofire), min(nofire) / float(max(fires))))
    exact = [w for w in procs if w == THRESHOLD]
    print("   cells with work EXACTLY at the threshold: %d %s"
          % (len(exact), "-> `<` vs `<=` is testable" if exact else "-> strictness UNTESTED"))
    print()

    llc = run("import scorch_ops as S;print(S.scorch_llc_bytes())")
    if llc is None:
        print("EXIT: scorch_llc_bytes is not exported, so maxout cannot be composed and")
        print("      leg 3 would be an upper bound presented as a prediction.")
        return 1
    maxout = 2 * llc          # SCORCH_SPMM_PARTITION_MAXOUT_LLC is 2L at :534
    print("llc_bytes from the build: %d (%.1f MiB), so maxout = %d"
          % (llc, llc / 1048576.0, maxout))
    pred, work_only = predicted(maxout)
    pred_live = {c for c in CELLS if c[0] * c[2] * 4 < maxout}
    print("\nLEG 3  all four predicates composed, in source order.")
    print("   at the BIG pool the ceiling fires, so the work gate is skipped and the only")
    print("   exclusion is maxout:            predicted live  %d of %d" % (len(pred_live), len(CELLS)))
    print("   at the SMALL pool it does not, so the work gate applies on top:")
    print("     work gate alone (upper bound)  %d" % len(work_only))
    print("     composed with maxout           %d   removes %r"
          % (len(pred), sorted(work_only - pred)))
    # the prediction's sensitivity to the one host constant it contains
    inv = []
    for cand in (16777216, 33554432, 50000000, 64000000, 67108864):
        m = 2 * cand
        lv = sum(1 for c in CELLS if c[0] * c[2] * 4 < m)
        at = sum(1 for c in CELLS if c[0] * c[2] * 4 < m and c[1] * max(c[2], 16) < THRESHOLD)
        inv.append((cand, lv, at))
    same = [c for c, lv, at in inv if (lv, at) == (len(pred_live), len(pred))]
    print("   SENSITIVITY to llc_bytes, the one host constant in the prediction:")
    for cand, lv, at in inv:
        print("     llc=%-10d  live %3d  attributable %2d%s"
              % (cand, lv, at, "   <- as measured" if cand == llc else ""))
    print("   the prediction is CONSTANT for llc in (32000000, 64000000] bytes -- which is")
    print("   exactly the bound the elem_size probe gives -- and changes outside it. So the")
    print("   result does not need llc known exactly, only bounded; it is not host-free.")

    # ---- does nthreads reach the answer at all? With its control.
    print("\nNTHREADS: the only predicate reading nthreads is the solo gate, and")
    print("   SCORCH_SPMM_PARTITION_SOLO_OFF is 0 at :531, so it cannot fire in a shipped")
    print("   build. If that reading is right, partition_mode is INDEPENDENT of nthreads")
    print("   and a sweep that recomputed nthreads from the pool was never confounded.")
    for pool in (small, big):
        ref = modes(1, pool, CELLS)
        if ref is None:
            continue
        diffs = []
        for nt in (2, 8, 32, 128):
            got = modes(nt, pool, CELLS)
            diffs.append("nt=%d:%d" % (nt, sum(1 for a, b in zip(ref, got) if a != b)
                                       if got else -1))
        print("   pool %-4d cells differing from nt=1 --  %s" % (pool, "  ".join(diffs)))
    ref = modes(1, small, CELLS, {"SCORCH_SPMM_PARTITION_SOLO_OFF": "1"})
    got = modes(8, small, CELLS, {"SCORCH_SPMM_PARTITION_SOLO_OFF": "1"})
    if ref and got:
        print("   CONTROL, solo gate ENABLED: nt=8 vs nt=1 -> %d cells differ. Without this"
              % sum(1 for a, b in zip(ref, got) if a != b))
        print("   row the zeros above would be indistinguishable from a probe that cannot")
        print("   vary nthreads at all.")

    # ---- LEG 1, and the two invariances
    print("\nLEG 1  isolation: resolved count HELD, only the pool varies")
    print("   %-10s %-12s %-12s %-10s %s"
          % ("nthreads", "attributable", "live", "share", "matches prediction"))
    attrib_sets = {}
    # 1 is in this set deliberately. The predicate being controlled for is
    # `nthreads <= 1`, so a held set of 2,4,8,16,32 is false at every value and the
    # invariance could not have failed even on a build where solo_off were live. HELD
    # VALUES MUST STRADDLE THE BOUNDARY OF THE PREDICATE BEING CONTROLLED FOR.
    for nt in (1, 2, 4, 8, 16, 32):
        a = modes(nt, small, CELLS)
        b = modes(nt, big, CELLS)
        if a is None or b is None:
            continue
        live = {CELLS[i] for i in range(len(CELLS)) if b[i] != 0}
        att = {CELLS[i] for i in range(len(CELLS)) if b[i] != 0 and a[i] == 0}
        attrib_sets[nt] = att
        miss = pred - att
        print("   %-10d %-12d %-12d %-10s %s"
              % (nt, len(att), len(live),
                 "%.1f%%" % (100.0 * len(att) / len(live)) if live else "n/a",
                 "exact" if att == pred else "%d predicted not attributed, %d extra"
                 % (len(miss), len(att - pred))))
    if attrib_sets:
        base = next(iter(attrib_sets.values()))
        same = all(v == base for v in attrib_sets.values())
        print("   INVARIANCE over held thread count: %s (the predicate has no thread term)"
              % ("identical sets" if same else "SETS DIFFER -- the isolation failed"))
        byrow = {}
        for (r, n, k) in base:
            byrow.setdefault(r, set()).add((n, k))
        vals = list(byrow.values())
        print("   INVARIANCE over rows: %s (the predicate never reads rows)"
              % ("identical (nnz,k) set at all %d row values" % len(byrow)
                 if vals and all(v == vals[0] for v in vals)
                 else "DIFFERS by row -- %r" % {r: len(v) for r, v in byrow.items()}))
        miss = sorted(pred - base)
        if miss:
            print("\n   the %d predicted cell(s) NOT attributed, with why:" % len(miss))
            idx = {c: i for i, c in enumerate(CELLS)}
            a = modes(8, small, CELLS)
            b = modes(8, big, CELLS)
            for c in miss:
                print("      %r  mode at pool %d = %d, at pool %d = %d -> %s"
                      % (c, small, a[idx[c]], big, b[idx[c]],
                         "already 0 at the big pool, so not live and not attributable"
                         if b[idx[c]] == 0 else "UNEXPLAINED"))

    # ---- the one predicate in this function that can read `rows`
    print("\nROWS: exactly one of the five predicates in scorch_spmm_partition_mode reads")
    print("   rows -- `rows * out_cols * elem_size >= maxout`. So any row-dependent")
    print("   exclusion must be that gate. Testing it behaviourally: at elem_size 8 the")
    print("   exclusion must MOVE from k=32 to k=16, since the product doubles.")
    for esz in (4, 8):
        cells = [(1000000, 3000, k) for k in (8, 16, 32)]
        got = run("import json,scorch_ops as S;print(json.dumps("
                  "[S.scorch_spmm_partition_mode(r,n,k,k,%d,8,%d) for (r,n,k) in %r]))"
                  % (esz, big, cells))
        if got is None:
            continue
        print("   elem_size=%d  rows=1e6 nnz=3000:  %s" % (esz, "  ".join(
            "k=%d product=%d mode=%d" % (k, 1000000 * k * esz, m)
            for (_, _, k), m in zip(cells, got))))
    print("   if the exclusion did not move, the single-predicate identification is WRONG")
    print("   and that is the more useful outcome than confirming the bound.")

    # ---- LEG 2, the two env routes, plus the default control
    print("\nLEG 2  two routes to 'gate off', and the control that matters most")
    print("   note: 0 is NOT 'off' for the ceiling -- it skips the `> 0` block, leaving")
    print("   mingrains at its default and the work gate ACTIVE at every pool.")
    base = modes(8, small, CELLS, {"SCORCH_SPMM_PARTITION_GATE_MAXTHREADS": "16"})
    if base is None:
        return 1
    print("   %-38s %-12s %s" % ("arm", "mode != 0", "moved vs shipped"))
    print("   %-38s %-12d %s" % ("MAXTHREADS=16  (shipped)", sum(1 for m in base if m), "-"))
    routes = {}
    for lbl, env in (("MAXTHREADS=4   (ceiling fires)", {"SCORCH_SPMM_PARTITION_GATE_MAXTHREADS": "4"}),
                     ("MINGRAINS=0    (gate left out)", {"SCORCH_SPMM_PARTITION_MINGRAINS": "0"}),
                     ("MINGRAINS=2    (COMPILED DEFAULT, control)", {"SCORCH_SPMM_PARTITION_MINGRAINS": "2"})):
        got = modes(8, small, CELLS, env)
        if got is None:
            continue
        moved = {CELLS[i] for i in range(len(CELLS)) if base[i] != got[i]}
        routes[lbl] = moved
        print("   %-38s %-12d %d" % (lbl, sum(1 for m in got if m), len(moved)))
    ctl = next((v for k, v in routes.items() if "COMPILED DEFAULT" in k), None)
    if ctl is not None:
        print("   CONTROL: setting a knob to its compiled default moved %d cells. It must be"
              % len(ctl))
        print("   0 -- this is the only check that separates a live hook from a live hook")
        print("   whose linked object carries a different default than the header.")
    a = routes.get("MAXTHREADS=4   (ceiling fires)", set())
    b = routes.get("MINGRAINS=0    (gate left out)", set())
    if a or b:
        print("   the two routes agree on %d cells and disagree on %d" % (len(a & b), len(a ^ b)))
        print("   both routes vs the closed-form prediction: %s"
              % ("exact on both" if a == pred and b == pred
                 else "route A %s, route B %s" % (
                     "exact" if a == pred else "differs by %d" % len(a ^ pred),
                     "exact" if b == pred else "differs by %d" % len(b ^ pred))))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
