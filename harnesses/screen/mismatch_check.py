#!/usr/bin/env python3
"""Classify cells the board recorded as answer mismatches.

full_api.py calls a cell a mismatch when scorch.matmul and torch.sparse.mm differ by more than
1e-4 in relative Frobenius norm. Both answers are rounded, so on an ill-conditioned matrix they can
disagree by more than that while both are as accurate as the dtype allows. This settles which: for
every listed cell it computes the exact product in float64 from the same inputs (B is generated by
the board's own seed rule) and reports, for scorch and for MKL separately,

  rel    ||C - C_exact|| / ||C_exact||       (the board's criterion, against the truth this time)
  bound  max_ij |C - C_exact|_ij / (eps * (|A||B|)_ij)   -- the standard forward-error bound of a
         dot product is n * eps * (|A||B|)_ij, so a value near the row length is the expected
         worst case for any summation order, and a value far beyond it is a wrong answer.

A cell is a rounding disagreement when scorch's bound is within the range MKL's is; it is a defect
when scorch's bound is orders of magnitude beyond MKL's or beyond the row length.

usage: mismatch_check.py <cache_dir> <cells_csv> <out_csv>
  cells_csv lines: corpus,key,k (header optional); SCREEN_DTYPE=float64 for double.
"""
import csv, os, sys, zlib
import numpy as np, torch, scorch
from scorch import STensor
sys.path.insert(0, "/matx/u/bobbyy/pfsstage")
from csrresolve import resolve_all
TDT, NDT = {"float32": (torch.float32, np.float32), "float64": (torch.float64, np.float64)}[
    os.environ.get("SCREEN_DTYPE", "float32")]
cache, cellsf, out = sys.argv[1:4]
cells = [l.strip().split(",")[:3] for l in open(cellsf) if l.strip() and not l.startswith("corpus")]
eps = float(torch.finfo(TDT).eps)
w = csv.writer(open(out, "w"))
w.writerow(["corpus", "key", "k", "rows", "nnz", "maxdeg", "arm", "rel", "bound_max", "bound_p99",
            "max_abs_value_ratio"])
by_corpus = {}
for c, key, k in cells: by_corpus.setdefault(c, []).append((key, int(k)))
for corpus, items in by_corpus.items():
    paths, _, _ = resolve_all(os.path.join(cache, corpus), sorted({k for k, _ in items}))
    for key, k in items:
        z = np.load(paths[key]); M, J = int(z["shape"][0]), int(z["shape"][1])
        ip, ix = z["indptr"].astype(np.int64), z["indices"].astype(np.int64)
        v = z["data"].astype(NDT)
        maxdeg = int(np.diff(ip).max()) if M else 0
        A = torch.sparse_csr_tensor(torch.from_numpy(ip.astype(np.int32)),
                                    torch.from_numpy(ix.astype(np.int32)), torch.from_numpy(v), size=(M, J))
        St = STensor.from_csr(torch.sparse_csr_tensor(torch.from_numpy(ip), torch.from_numpy(ix),
                                                      torch.from_numpy(v), size=(M, J)), "A")
        g = torch.Generator().manual_seed(zlib.crc32(("%s|%d" % (key, k)).encode()) % (2**31))
        B = torch.rand((J, k), generator=g, dtype=TDT)
        A64 = torch.sparse_csr_tensor(torch.from_numpy(ip), torch.from_numpy(ix),
                                      torch.from_numpy(v.astype(np.float64)), size=(M, J))
        Aabs = torch.sparse_csr_tensor(torch.from_numpy(ip), torch.from_numpy(ix),
                                       torch.from_numpy(np.abs(v.astype(np.float64))), size=(M, J))
        exact = torch.sparse.mm(A64, B.double())
        mag = torch.sparse.mm(Aabs, B.double().abs())
        vr = float(np.abs(v).max() / max(np.abs(v[v != 0]).min(), 1e-300)) if v.size else 0.0
        for arm, C in (("scorch", scorch.matmul(St, B)), ("mkl", torch.sparse.mm(A, B))):
            d = (C.double() - exact).abs()
            rel = float(d.norm() / max(float(exact.norm()), 1e-300))
            r = (d / (eps * mag).clamp_min(1e-300)).flatten()
            r = r[mag.flatten() > 0]
            bmax = float(r.max()) if r.numel() else 0.0
            bp99 = float(torch.quantile(r[:1 << 24].float(), 0.99)) if r.numel() else 0.0
            w.writerow([corpus, key, k, M, int(ip[-1]), maxdeg, arm, "%.3e" % rel, "%.3g" % bmax,
                        "%.3g" % bp99, "%.3g" % vr])
